def is_text(b: int) -> bool:
    return b >= 0x51 or 0x20 <= b <= 0x23 or b in (0x18, 0x46)


def glyph_len(b: int) -> int:
    return 1 if b >= 0x51 else 2


def op_len(rom: bytes, a: int) -> int | None:
    b = rom[a]
    if is_text(b):
        return glyph_len(b)
    if b == 0x0D:
        m = rom[a + 1]
        return None if m == 0x20 else D_MODE_LEN.get(m)
    if b == 0x3C:
        return 3 if rom[a + 1] == 0xFF else 4
    if b == 0x48:
        return 3 + max(1, rom[a + 2])
    if b == 0x4F:
        return CONTROL_4F.get(rom[a + 1])
    if b == 0x49:
        m = rom[a + 1]
        return 4 if m <= 3 else 3 if m in (4, 5) else 2
    return CONTROL_LEN.get(b)


def ops(rom: bytes, start: int, end: int):
    """Linear decode; only valid when start is a known op boundary."""
    a = start
    while a < end:
        n = op_len(rom, a)
        if not n:
            yield a, 0, "unknown"
            return
        b = rom[a]
        kind = "glyph" if is_text(b) else NAMES.get(b, f"op{b:02X}")
        yield a, n, kind
        a += n
